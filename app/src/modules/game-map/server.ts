export function getMap() {
  const sections = mapWith(
    CONFIG.scene.sections,
    (helper, section) => {
      const {model, size, positions} =
        CONFIG.sections[section as keyof typeof CONFIG.sections];

      helper.offset += size;

      return {
        model,
        positions,
        offset: helper.offset - size,
      };
    },
    {
      offset: 0,
    },
  );

  const positions = sections.flatMap(({positions, offset}) => {
    return positions.map(([x, z]) => {
      return {
        x: x + offset,
        z: z + offset,
      };
    });
  });

  positions.sort((a, b) => {
    if (a.z !== b.z) {
      return a.z - b.z;
    }

    return a.x - b.x;
  });

  const z = groupOf(
    mapWith(
      positions,
      (helper, value, i) => {
        const {x, z} = value;
        const {x: x0, z: z0} = helper;

        helper.x = x;
        helper.z = z;

        if (z0 !== z) {
          return [z0, x0];
        }

        if (x - x0 > 1) {
          return [z0, x0];
        }

        if (i === positions.length - 1) {
          return [z, x];
        }
      },
      {
        x: positions[0].x,
        z: positions[0].z,
      },
    ),
  );

  positions.sort((a, b) => {
    if (a.x !== b.x) {
      return a.x - b.x;
    }

    return a.z - b.z;
  });

  const x = groupOf(
    mapWith(
      positions,
      (helper, value, i) => {
        const {x, z} = value;
        const {x: x0, z: z0} = helper;

        helper.x = x;
        helper.z = z;

        if (x0 !== x) {
          return [x0, z0];
        }

        if (z - z0 > 1) {
          return [x0, z0];
        }

        if (i === positions.length - 1) {
          return [x, z];
        }
      },
      {
        x: positions[0].x,
        z: positions[0].z,
      },
    ),
  );

  return {
    sections,
    positions,
    boundaries: {
      x,
      z,
    },
  };
}
